export function setupDesktopPointerCapture(engineApi) {
  if (typeof window === 'undefined' || typeof document === 'undefined') return false;
  const controls = (stageConfig && stageConfig.controls) ? stageConfig.controls : {};
  const pointerLockEnabled = controls.enablePointerLock === true || controls.enablePointerLock === 'true';
  if (!pointerLockEnabled) return false;

  const isMobile = (engineApi && typeof engineApi.isMobileInUse === 'function')
    ? engineApi.isMobileInUse()
    : (typeof window.isMobileInUse === 'function' ? window.isMobileInUse() : false);
  if (isMobile) return false;

  // Bind desktop click-to-capture and ESC-to-release coordinator once across all stage transitions
  if (!window._wormholeDesktopPointerCaptureBound) {
    const getTargetContainer = () => {
      if (engineApi && typeof engineApi.getCanvasContainer === 'function') {
        const c = engineApi.getCanvasContainer();
        if (c) return c;
      }
      return document.getElementById('webgl-container');
    };

    const isInteractiveTarget = (target) => {
      if (!target || typeof target.closest !== 'function') return false;
      return !!target.closest(
        '#game-over-modal, #game-countdown-overlay, .device-modal-overlay, ' +
        '#left-drawer-container, #top-drawer-container, #bottom-drawer-container, ' +
        '#mobile-touch-controls, #unsupported-device-modal, .weapon-wheel-overlay, ' +
        '#wormhole-splash-screen, .hud-weapon-pill, .hud-btn, .drawer-pause-btn, ' +
        '.hud-pause-icon-btn, .hud-exit-icon-btn, button, input, select, textarea, a, [role="button"], [role="tab"]'
      );
    };

    const canCaptureNow = () => {
      const st = window.state;
      if (!st) return false;
      if (st.isPaused || st.isGameOver || st.isCountdownActive || st.isXR) return false;
      if (st.desktopPointerLockEnabled === false) return false;
      if (typeof window.isMobileInUse === 'function' && window.isMobileInUse()) return false;
      const splash = document.getElementById('wormhole-splash-screen');
      if (splash && splash.parentNode && window.getComputedStyle(splash).display !== 'none' && !splash.classList.contains('splash-fade-out')) {
        return false;
      }
      const wheel = document.getElementById('weapon-wheel-overlay');
      if (wheel && window.getComputedStyle(wheel).display === 'flex') return false;
      return true;
    };

    const triggerCapture = () => {
      if (!canCaptureNow()) return false;
      if (typeof window.requestCrosshairCapture === 'function') {
        return window.requestCrosshairCapture(false, { fromUserGesture: true, source: 'desktop-stage' });
      }
      const targetEl = getTargetContainer();
      if (targetEl && document.pointerLockElement !== targetEl && typeof targetEl.requestPointerLock === 'function') {
        try {
          const p = targetEl.requestPointerLock();
          if (p && typeof p.catch === 'function') p.catch(() => {});
          return true;
        } catch (e) {}
      }
      return false;
    };

    const triggerRelease = (reason = 'escape') => {
      if (typeof window.releaseCrosshairCapture === 'function') {
        window.releaseCrosshairCapture(reason);
        return;
      }
      if (document.pointerLockElement && typeof document.exitPointerLock === 'function') {
        try { document.exitPointerLock(); } catch (e) {}
      }
      if (window.state) {
        window.state.isPointerLocked = false;
        window.state.isLeftMouseDown = false;
        window.state.isRightMouseDown = false;
        window.state.isMouseDown = false;
        window.state.lastPointerLockExitTime = performance.now();
      }
      if (document.body) {
        document.body.classList.remove('crosshair-captured');
      }
    };

    // Capture mouse cursor into crosshair on gameplay click
    window.addEventListener('click', (e) => {
      if (e.button !== 0) return;
      if (e.pointerType === 'touch' || (e.sourceCapabilities && e.sourceCapabilities.firesTouchEvents)) return;
      if (isInteractiveTarget(e.target)) return;
      if (!canCaptureNow()) return;
      const targetEl = getTargetContainer();
      const alreadyLocked = !!(document.pointerLockElement && targetEl && (document.pointerLockElement === targetEl || targetEl.contains(document.pointerLockElement)));
      if (!alreadyLocked || (window.state && !window.state.isPointerLocked)) {
        triggerCapture();
      }
    }, false);

    // Release captured mouse cursor immediately when Escape key is pressed
    window.addEventListener('keydown', (e) => {
      if (e.code !== 'Escape' && e.key !== 'Escape') return;
      const st = window.state;
      const targetEl = getTargetContainer();
      const lockedNow = !!(document.pointerLockElement && (!targetEl || document.pointerLockElement === targetEl || targetEl.contains(document.pointerLockElement)));
      if (lockedNow || (st && st.isPointerLocked)) {
        e.preventDefault();
        e.stopPropagation();
        triggerRelease('escape');
      }
    }, true);

    window._wormholeDesktopPointerCaptureBound = true;
    window._wormholeDesktopTriggerCapture = triggerCapture;
    window._wormholeDesktopTriggerRelease = triggerRelease;
  }

  // On every desktop stage entry, synchronize and arm pointer capture cleanly
  const stageTag = 'stage_' + (stageConfig && (stageConfig.stage_level || (stageConfig.meta && stageConfig.meta.level)) ? (stageConfig.stage_level || stageConfig.meta.level) : 1) + '_applyStage';
  if (engineApi && typeof engineApi.armDesktopPointerCapture === 'function') {
    engineApi.armDesktopPointerCapture(stageTag);
  } else if (typeof window.armDesktopPointerCaptureForStage === 'function') {
    window.armDesktopPointerCaptureForStage(stageTag);
  } else if (typeof window.requestCrosshairCapture === 'function' && window.state && window.state.hasStarted && !window.state.isPaused && !window.state.isGameOver && !window.state.isCountdownActive) {
    window.requestCrosshairCapture(false, { source: stageTag });
  }

  return true;
}

export function applyStage(engineApi) {
  if (!engineApi) return stageConfig;
  console.log('[Stage 1: ' + "Warp Origin" + '] Applying VR Headset Profile configuration...');

  if (typeof engineApi.setThemeColors === 'function') {
    engineApi.setThemeColors(stageConfig.visual);
  }
  if (typeof engineApi.setHudStatus === 'function') {
    engineApi.setHudStatus("STAGE 1: WARP ORIGIN [VR]");
  }
  if (typeof engineApi.setFlightConfig === 'function') {
    engineApi.setFlightConfig(stageConfig.visual.flight);
  }
  if (typeof engineApi.setWeapons === 'function') {
    engineApi.setWeapons(stageConfig.weapons);
  }
  if (typeof engineApi.setEnemies === 'function') {
    engineApi.setEnemies(stageConfig.enemies);
  }
  ensureWarpOriginProceduralEnemies();
  if (typeof engineApi.setPowerups === 'function' && stageConfig.powerups) {
    engineApi.setPowerups(stageConfig.powerups);
  }
  if (typeof engineApi.setEnvironment === 'function' && stageConfig.environment) {
    engineApi.setEnvironment(stageConfig.environment);
  }
  if (typeof engineApi.setStageObjectives === 'function') {
    engineApi.setStageObjectives(stageConfig.objectives || []);
  }
  if (typeof engineApi.setDeviceControls === 'function') {
    engineApi.setDeviceControls(stageConfig.controls);
  }
  if (typeof engineApi.setEnemyMovementHandler === 'function') {
    engineApi.setEnemyMovementHandler(updateEnemyMovement);
  }
  if (typeof engineApi.setEnemyWeaponHandler === 'function') {
    engineApi.setEnemyWeaponHandler(fireEnemyWeapon);
  }
  if (typeof engineApi.setStageWaveHandler === 'function') {
    engineApi.setStageWaveHandler(updateStageWaves);
  }
  if (typeof engineApi.showToast === 'function') {
    engineApi.showToast("🚀 STAGE 1: WARP ORIGIN [VR] LOADED");
  }

  // --- Bind Stage 1's Two Separate Procedural Enemy Pools & Mount Cockpit Overlay via Pool ---
  const camera = (engineApi && engineApi.camera) || (typeof window !== 'undefined' && window.camera);
  const scene = (engineApi && engineApi.scene) || (typeof window !== 'undefined' && window.scene);
  const proceduralEnemyPools = ensureStageProceduralEnemyPools(engineApi, scene);
  const pool = (engineApi && typeof engineApi.getObjectPool === 'function' ? engineApi.getObjectPool() : null)
    || activeStageObjectPool
    || (typeof window !== 'undefined' && window.stageObjectPool)
    || null;

  setupCockpitCracksOverlay(camera, pool, scene);

  // Resize and orientation handlers to maintain perfect cockpit fit dynamically scaling overlay with FOV
  if (typeof window !== 'undefined') {
    if (!window._cockpitCracksResizeBound) {
      const onResizeFit = () => {
        const inXr = !!(window.renderer && window.renderer.xr && window.renderer.xr.isPresenting);
        let cam = window.camera;
        if (inXr && window.renderer.xr && typeof window.renderer.xr.getCamera === 'function') {
          const xrCam = window.renderer.xr.getCamera();
          if (xrCam && Array.isArray(xrCam.cameras) && xrCam.cameras.length > 0) {
            cam = xrCam.cameras[0];
          } else if (xrCam) {
            cam = xrCam;
          }
        }
        const ov = (typeof window.getActiveCockpitCracksOverlay === 'function' ? window.getActiveCockpitCracksOverlay() : null) || getActiveOverlay();
        if (ov && cam && typeof window.fitCockpitCracksToCamera === 'function') {
          window.fitCockpitCracksToCamera(ov, cam);
        }
      };
      window.addEventListener('resize', onResizeFit);
      window.addEventListener('orientationchange', () => setTimeout(onResizeFit, 200));
      window._cockpitCracksResizeBound = true;
    }

    // Hook enemy hit detection:
    if (typeof window.applyDamageToPlayer === 'function') {
      const baseDamage = window.applyDamageToPlayer._baseApplyDamage || window.applyDamageToPlayer;
      const wrappedApplyDamage = function(dmg, ...args) {
        const weapon = args[0] || (typeof dmg === 'object' ? dmg : null);
        // Weapon Range Gate (10,000 KM): enemy weapons fired from > 10,000 KM cannot hit or damage the player
        if (weapon && typeof weapon === 'object' && (weapon.canHitPlayer === false || weapon.firedWithinRange === false)) {
          return;
        }
        const st = (typeof window.state !== 'undefined' && window.state) ? window.state : null;
        const maxShield = (st && st.maxShield > 0) ? st.maxShield : 100;
        const maxHealth = (st && st.maxHealth > 0) ? st.maxHealth : 100;
        const shieldBefore = st && typeof st.playerShield === 'number' ? st.playerShield : maxShield;
        const healthBefore = st && typeof st.playerHealth === 'number' ? st.playerHealth : maxHealth;

        wrappedApplyDamage._inStageWrapper = true;
        let ret;
        try {
          ret = baseDamage.apply(this, [dmg, ...args]);
        } finally {
          wrappedApplyDamage._inStageWrapper = false;
        }

        const shieldAfter = st && typeof st.playerShield === 'number' ? st.playerShield : 0;
        const healthAfter = st && typeof st.playerHealth === 'number' ? st.playerHealth : maxHealth;

        // Only turn on a weapon decal when shield or health (whichever is being reduced)
        // drops by 100% / availableDecals (e.g., 100 / 18 = 5.55% per decal)
        triggerCockpitCracksHit(weapon, 280, {
          shieldBefore,
          shieldAfter,
          healthBefore,
          healthAfter,
          maxShield,
          maxHealth
        });

        // When shield reaches 0%, BrokenSpiderWeb Core decal remains on unless shield % increases back above 0%
        if (shieldAfter <= 0 || healthAfter <= 0) {
          triggerShieldDepletedCockpitCracks(true);
        } else if (shieldAfter > 0 && healthAfter > 0) {
          triggerShieldDepletedCockpitCracks(false);
        }

        // When health reaches 0%, both BrokenSpiderWeb Core and BrokenSpiderWeb Screen decals turn on for 4 seconds
        if (healthAfter <= 0) {
          triggerGameOverCockpitCracks(4000);
        } else if (shieldAfter >= maxShield - 1e-6 && healthAfter >= maxHealth - 1e-6) {
          clearCockpitDecalsIfFullDefense(null, 100, 100);
        }

        return ret;
      };
      wrappedApplyDamage._cockpitCracksHooked = true;
      wrappedApplyDamage._baseApplyDamage = baseDamage;
      wrappedApplyDamage._inStageWrapper = false;
      window.applyDamageToPlayer = wrappedApplyDamage;
    }

    // Hook powerup restoration so when both health and shield reach 100%, all active decals turn off
    if (typeof window.applyPowerupEffect === 'function') {
      const basePowerupEffect = window.applyPowerupEffect._baseApplyPowerupEffect || window.applyPowerupEffect;
      const wrappedPowerupEffect = function(powerupInstance, ...args) {
        const ret = basePowerupEffect.apply(this, [powerupInstance, ...args]);
        const st = (typeof window.state !== 'undefined' && window.state) ? window.state : null;
        const maxShield = (st && st.maxShield > 0) ? st.maxShield : 100;
        const maxHealth = (st && st.maxHealth > 0) ? st.maxHealth : 100;
        const shieldPct = (st && typeof st.playerShield === 'number') ? Math.max(0, Math.min(100, (st.playerShield / maxShield) * 100)) : null;
        const healthPct = (st && typeof st.playerHealth === 'number') ? Math.max(0, Math.min(100, (st.playerHealth / maxHealth) * 100)) : null;
        if (shieldPct !== null && healthPct !== null) {
          syncCockpitDecalThreshold(null, shieldPct, healthPct);
          clearCockpitDecalsIfFullDefense(null, shieldPct, healthPct);
        }
        return ret;
      };
      wrappedPowerupEffect._cockpitDecalsHooked = true;
      wrappedPowerupEffect._baseApplyPowerupEffect = basePowerupEffect;
      window.applyPowerupEffect = wrappedPowerupEffect;
    }

    if (!window._cockpitCracksEventsBound) {
      window.addEventListener('cockpitHit', (e) => window.triggerCockpitCracksHit && window.triggerCockpitCracksHit(e.detail));
      window.addEventListener('playerDamage', (e) => window.triggerCockpitCracksHit && window.triggerCockpitCracksHit(e.detail));
      window.addEventListener('cockpitImpact', (e) => window.triggerCockpitCracksHit && window.triggerCockpitCracksHit(e.detail));
      window.addEventListener('shieldDepleted', () => window.triggerShieldDepletedCockpitCracks && window.triggerShieldDepletedCockpitCracks());
      window.addEventListener('gameOverCracks', () => window.triggerGameOverCockpitCracks && window.triggerGameOverCockpitCracks(4000));
      window._cockpitCracksEventsBound = true;
    }

    const baseCustomFx = (window.executeCustomWeaponImpactFx && window.executeCustomWeaponImpactFx._baseCustomFx) || window.executeCustomWeaponImpactFx;
    const wrappedCustomFx = function(bolt, normX, normY, canvas) {
      if (typeof baseCustomFx === 'function') {
        try { baseCustomFx(bolt, normX, normY, canvas); } catch (e) {}
      }
      triggerCockpitCracksHit(bolt);
    };
    wrappedCustomFx._baseCustomFx = baseCustomFx;
    window.executeCustomWeaponImpactFx = wrappedCustomFx;

    window.triggerCockpitCracksHit = triggerCockpitCracksHit;
    window.triggerCockpitOverlayHit = triggerCockpitCracksHit;
    window.flashCockpitCracks = triggerCockpitCracksHit;
    window.triggerShieldDepletedCockpitCracks = triggerShieldDepletedCockpitCracks;
    window.triggerGameOverCockpitCracks = triggerGameOverCockpitCracks;
    window.hideCockpitCracks = hideCockpitCracks;
    window.resetCockpitOverlayDecals = resetCockpitOverlayDecals;
    window.setupCockpitCracksOverlay = setupCockpitCracksOverlay;
    window.setupCockpitOverlayHierarchy = setupCockpitCracksHierarchy;
    window.fitCockpitCracksToCamera = fitCockpitCracksToCamera;
    window.fitCockpitOverlayToCamera = fitCockpitCracksToCamera;
    window.getActiveCockpitCracksOverlay = getActiveCockpitCracksOverlay;
    window.getAvailableCockpitDecalCount = getAvailableCockpitDecalCount;
    window.resetCockpitDecalThreshold = resetCockpitDecalThreshold;
    window.syncCockpitDecalThreshold = syncCockpitDecalThreshold;
    window.evaluateWeaponDecalThreshold = evaluateWeaponDecalThreshold;
    window.hasAnyCockpitDecalActive = hasAnyCockpitDecalActive;
    window.clearCockpitDecalsIfFullDefense = clearCockpitDecalsIfFullDefense;
    window.WEAPON_MAX_RANGE_KM = WEAPON_MAX_RANGE_KM;
    window.WEAPON_MAX_RANGE_UNITS = WEAPON_MAX_RANGE_UNITS;
    window.isEnemyWithinWeaponRange = isEnemyWithinWeaponRange;
    window.canEnemyHitPlayer = canEnemyHitPlayer;
    window.canPlayerDestroyEnemy = canPlayerDestroyEnemy;
    window.stageProceduralEnemyPools = proceduralEnemyPools || (pool && typeof pool.getProceduralEnemyPools === 'function' ? pool.getProceduralEnemyPools() : null);
    window.stageProceduralEnemyPool = window.stageProceduralEnemyPools;
    window.stagePhaseInterceptorEnemyPool = (proceduralEnemyPools && proceduralEnemyPools.drone_phase_interceptor_3) || (pool && pool.interceptorProceduralEnemyPool) || null;
    window.stageInterceptorProceduralEnemyPool = window.stagePhaseInterceptorEnemyPool;
    window.stageReconDroneEnemyPool = (proceduralEnemyPools && proceduralEnemyPools['recon_drone_2.8m']) || (pool && pool.reconDroneProceduralEnemyPool) || null;
    window.stageReconDroneProceduralEnemyPool = window.stageReconDroneEnemyPool;
    window.getStageProceduralEnemyPools = getStageProceduralEnemyPools;
    window.getStageProceduralEnemyPool = getStageProceduralEnemyPool;
    window.spawnProceduralEnemyFromPool = spawnProceduralEnemyFromPool;
    window.despawnProceduralEnemyToPool = despawnProceduralEnemyToPool;

    window.setupDesktopPointerCapture = setupDesktopPointerCapture;
    clearCockpitDecalsIfFullDefense();
    setupDesktopPointerCapture(engineApi);
  }

  return stageConfig;
}

